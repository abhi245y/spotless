#!/usr/bin/env python3
"""Deterministic, digest-pinned offline Spotify frontend patch. No network I/O."""
import argparse
import hashlib
import json
from pathlib import Path

SOURCE_SHA256 = "bccd77047ca9bcda924c1de15f0d9990ce9eb420a5ea0733f5f75f27a47d5ebb"
HERE = Path(__file__).resolve().parent
NEEDS_ORIGINAL = "void 0!==n.isLinked&&(l.needsLinking=!n.isLinked&&!n.isGuest)"
NEEDS_PATCHED = "void 0!==n.isLinked&&(l.needsLinking=!n.isLinked&&!n.isGuest&&!(window.__spotifyStandaloneAuth===true&&n.isStandaloneAuth===true&&n.bridgeSession))"
SCOPE_ORIGINAL = 'e.ps5GlobalObject.msdk.connectAccount.setAdditionalScope("psn:app.spotify").then(function(e){}).catch(function(e){})'
SCOPE_PATCHED = "window.__spotifyStandaloneAuth===true||" + SCOPE_ORIGINAL
DEEPLINK_START = "a.getSignedInLinkedUserPromise=function(){"
DEEPLINK_END = ",a.handleLaunchArgs="
DEEPLINK_REPLACEMENT = """a.getSignedInLinkedUserPromise=function(){
var platform=this;
return new Promise(function(resolve,reject){
platform.sessionsHandler.sessionObservable.subscribe(function(session,subscription,previous){
try{
var standalone=window.__spotifyStandaloneAuth===true&&session&&session.isStandaloneAuth===true&&session.bridgeSession&&session.bridgeSession===platform.sessionsHandler._bridgeSessionsHandler.sessionObservable.getState();
if(session&&session.isLinked===true||standalone){subscription.unsubscribe();resolve();return;}
if(previous&&!session){subscription.unsubscribe();reject();}
}catch(error){try{subscription.unsubscribe();}catch(ignore){}reject(error);}
});
});
}"""


def digest(data):
    return hashlib.sha256(data).hexdigest()


def c_string(data):
    out = []
    for byte in data:
        if byte == 10:
            out.append('\\n"\n    "')
        elif 32 <= byte < 127 and byte not in b'\\"?':
            out.append(chr(byte))
        else:
            out.append('\\%03o' % byte)
    return '"' + ''.join(out) + '"'


def payload_header(source, result, ordered):
    """Edits as minimal deletions/insertions, so the payload carries no Spotify code."""
    lines = ["/* Generated by frontend/standalone/build_patch.py. Do not edit. */",
             "#define SP_PATCHED_SIZE %du" % len(result),
             "static const struct {",
             "  uint32_t offset, length, insert_length;",
             "  const char *insert;",
             "} sp_edits[] = {"]
    for start, stop, new, name in ordered:
        old = source[start:stop]
        prefix = 0
        while prefix < min(len(old), len(new)) and old[prefix] == new[prefix]:
            prefix += 1
        suffix = 0
        while suffix < min(len(old), len(new)) - prefix and old[-1 - suffix] == new[-1 - suffix]:
            suffix += 1
        insert = new[prefix:len(new) - suffix]
        lines.append("    /* %s */" % name)
        lines.append("    {%d, %d, %d,\n     %s}," % (start + prefix, len(old) - prefix - suffix,
                                                      len(insert), c_string(insert)))
    return "\n".join(lines) + "\n};\n"


def make_patch(source, shim):
    if digest(source) != SOURCE_SHA256:
        raise ValueError("Source digest mismatch; refusing an unknown frontend version")
    edits = []

    def edit(name, old, new):
        old, new = old.encode(), new.encode()
        if source.count(old) != 1:
            raise ValueError(f"Expected one exact anchor: {name}")
        start = source.index(old)
        edits.append((start, start + len(old), new, name))

    edit("explicit-standalone-mode", "!function(){var e,n,t,i,r,a=", "window.__spotifyStandaloneAuth=true;\n!function(){var e,n,t,i,r,a=")
    edit("install-authenticated-session-shim", ";function OG(e){", ";\n" + shim.decode() + "\nfunction OG(e){")
    edit("standalone-needs-linking", NEEDS_ORIGINAL, NEEDS_PATCHED)
    edit("skip-sony-additional-scope", SCOPE_ORIGINAL, SCOPE_PATCHED)
    start = source.index(DEEPLINK_START.encode())
    stop = source.index(DEEPLINK_END.encode(), start)
    edit("authenticated-deeplinks", source[start:stop].decode(), DEEPLINK_REPLACEMENT)
    edit("diagnostic-controller-export", "q$=W$,ji(\"js_parse\")", "q$=W$,window.__spotifyStandaloneController=W$,ji(\"js_parse\")")

    ordered = sorted(edits)
    for left, right in zip(ordered, ordered[1:]):
        if left[1] > right[0]:
            raise ValueError("Overlapping source edits")
    result = source
    for start, stop, replacement, _ in reversed(ordered):
        result = result[:start] + replacement + result[stop:]
    manifest = {
        "source_sha256": digest(source), "source_size": len(source),
        "patched_sha256": digest(result), "patched_size": len(result),
        "shim_sha256": digest(shim), "standalone_mode": True,
        "edits": [{"name": name, "source_byte_offset": start,
                   "source_length": stop - start, "replacement_length": len(new)}
                  for start, stop, new, name in ordered],
        "limitations": ["Tested on console with firmware 13.00",
                        "Native token/profile errors retain original behavior",
                        "Does not modify system music-card control center"]}
    return result, manifest, payload_header(source, result, ordered)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=HERE.parent / "spotifytv.js")
    parser.add_argument("--output", type=Path, default=HERE / "spotifytv.standalone.js")
    args = parser.parse_args()
    output, manifest, header = make_patch(args.input.read_bytes(), (HERE / "standalone-shim.js").read_bytes())
    if args.output.resolve() == args.input.resolve():
        raise ValueError("Refusing to overwrite original frontend")
    args.output.write_bytes(output)
    args.output.with_suffix(".manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (HERE.parents[1] / "payload/ui_patch.h").write_text(header)
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
